
# 9-16 Python Module of the Week: Explore the calendar module.
import calendar

# Show a calendar for November 2026.
print(calendar.month(2026, 11))

# Check if a year is a leap year.
print("Is 2028 a leap year?", calendar.isleap(2028))

# Show the calendar for a whole year.
print(calendar.calendar(2026))
